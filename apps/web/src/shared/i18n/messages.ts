export type MessageKey = keyof typeof messages.az
export type Locale = keyof typeof messages
export type Language = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: string) => string }

export function translate(locale: Locale, key: string) {
  return messages[locale][key as MessageKey] ?? messages[locale].generic
}

export function readStoredLocale(): Locale {
  try { return localStorage.getItem("turborent.locale") === "en" ? "en" : "az" } catch { return "az" }
}

/** Shared language state; provided once by LocaleProvider at the app root. */
export const LocaleContext = createContext<Language | null>(null)

export function useLocale(): Language {
  const context = useContext(LocaleContext)
  if (!context) throw new Error("useLocale must be used inside LocaleProvider.")
  return context
}
